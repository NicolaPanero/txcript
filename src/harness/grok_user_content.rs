use serde_json::Value;

use crate::common::{Block, Role};

pub(super) fn user_texts(content: &Value) -> impl Iterator<Item = &str> {
    let texts: Vec<&str> = match content {
        Value::String(text) => vec![text],
        Value::Array(blocks) => blocks
            .iter()
            .filter_map(|block| block.get("text").and_then(Value::as_str))
            .collect(),
        _ => Vec::new(),
    };
    texts.into_iter()
}

const RUNTIME_TAGS: &[&str] = &[
    "user_info",
    "project_layout",
    "git_status",
    "rules",
    "system-reminder",
    "system_reminder",
    "agent-memory",
    "background_context",
    "fork-context",
    "command-name",
    "command-message",
    "command-args",
];

fn tag_range(text: &str, tag: &str) -> Option<std::ops::Range<usize>> {
    let open = format!("<{tag}>");
    let start = text.find(&open)?;
    let close = format!("</{tag}>");
    let end = text.get(start + open.len()..)?.find(&close)? + start + open.len() + close.len();
    Some(start..end)
}

fn strip_runtime_tags(text: &str) -> String {
    let mut text = text.to_string();
    for tag in RUNTIME_TAGS {
        while let Some(range) = tag_range(&text, tag) {
            text.replace_range(range, "");
        }
    }
    text
}

fn strip_prefix_tags<'a>(mut text: &'a str, tags: &[&str]) -> &'a str {
    loop {
        let trimmed = text.trim_start();
        let Some(range) = tags
            .iter()
            .find_map(|tag| tag_range(trimmed, tag).filter(|r| r.start == 0))
        else {
            return text;
        };
        text = &trimmed[range.end..];
    }
}

fn extract_query(raw: &str) -> String {
    let text = strip_prefix_tags(raw, RUNTIME_TAGS).trim();
    if text.starts_with("<user_query>") && text.contains("</user_query>") {
        let query = query_text(text);
        strip_prefix_tags(query, &["system-reminder", "system_reminder"])
            .trim()
            .to_string()
    } else {
        text.to_string()
    }
}

fn query_text(text: &str) -> &str {
    let text = text.trim();
    if let Some(start) = text.find("<user_query>") {
        let rest = &text[start + "<user_query>".len()..];
        if let Some(end) = rest.rfind("</user_query>") {
            return rest[..end].trim();
        }
    }
    text
}

pub(super) fn matches_prompt(content: &Value, prompt: &str) -> bool {
    if prompt.is_empty() {
        return false;
    }
    user_texts(content).any(|raw| {
        raw.trim() == prompt.trim()
            || query_text(raw) == prompt.trim()
            || query_text(&strip_runtime_tags(raw)) == prompt.trim()
    })
}

pub(super) fn user_blocks(
    content: &Value,
    reason: Option<&str>,
    displayed: Option<&str>,
) -> (Role, Vec<Block>) {
    let human = matches!(
        reason,
        None | Some("human" | "interjection" | "parent_human_message")
    );
    if !human {
        if matches!(
            reason,
            Some(
                "primary"
                    | "session_prefix"
                    | "project_instructions"
                    | "system_reminder"
                    | "auto_continue"
                    | "length_continue"
                    | "auto_recovery"
                    | "working_directory_switch"
            )
        ) {
            return (Role::Assistant, vec![]);
        }
        return context_blocks(content);
    }
    if let Some(displayed) = displayed {
        return (
            Role::User,
            if displayed.is_empty() {
                vec![]
            } else {
                vec![Block::Text {
                    text: displayed.to_string(),
                }]
            },
        );
    }
    let blocks: Vec<Block> = user_texts(content)
        .filter_map(|raw| {
            if !raw.trim_start().starts_with('<') {
                return (!raw.trim().is_empty()).then(|| Block::Text {
                    text: raw.to_string(),
                });
            }
            let text = extract_query(raw);
            (!text.trim().is_empty() && text != "__auto_continue__").then_some(Block::Text { text })
        })
        .collect();
    if blocks.is_empty()
        && user_texts(content).any(|raw| raw.trim_start().starts_with("<fork-context>"))
    {
        return context_blocks(content);
    }
    (Role::User, blocks)
}

fn context_blocks(content: &Value) -> (Role, Vec<Block>) {
    let text = user_texts(content).collect::<Vec<_>>().join("\n");
    let blocks = if text.trim().is_empty() {
        vec![]
    } else {
        vec![Block::Text {
            text: format!(
                "[Imported Grok context, generated by the runtime rather than written by the user]\n{text}"
            ),
        }]
    };
    (Role::Assistant, blocks)
}
